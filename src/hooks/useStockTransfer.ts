import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useToast } from "@/hooks/use-toast";
import type { 
  StockTransferRequest, 
  StockTransferItem,
  CreateStockTransferData,
  CreateStockTransferItemData,
  TransferStatus
} from "@/types/stockTransfer";

export const useStockTransferRequests = (status?: TransferStatus) => {
  return useQuery({
    queryKey: ["stock-transfer-requests", status],
    queryFn: async () => {
      let query = supabase
        .from("stock_transfer_requests")
        .select("*")
        .order("created_at", { ascending: false });

      if (status) {
        query = query.eq("status", status);
      }

      const { data, error } = await query;
      if (error) throw error;
      return data as StockTransferRequest[];
    },
  });
};

export const useStockTransferItems = (transferId: string | undefined) => {
  return useQuery({
    queryKey: ["stock-transfer-items", transferId],
    queryFn: async () => {
      if (!transferId) return [];
      
      const { data, error } = await supabase
        .from("stock_transfer_items")
        .select("*")
        .eq("transfer_id", transferId)
        .order("created_at", { ascending: true });

      if (error) throw error;
      return data as StockTransferItem[];
    },
    enabled: !!transferId,
  });
};

export const useCreateStockTransfer = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (data: CreateStockTransferData) => {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) throw new Error("User not authenticated");

      const { data: transfer, error } = await supabase
        .from("stock_transfer_requests")
        .insert({
          ...data,
          transfer_number: '', // Auto-generated by trigger
          created_by: user.id,
          requested_by: user.id,
          // Auto-set approval info if status is 'approved' (skip approval workflow)
          ...(data.status === 'approved' && {
            approved_by: user.id,
            approved_date: new Date().toISOString(),
          }),
        })
        .select()
        .single();

      if (error) throw error;
      return transfer as StockTransferRequest;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["stock-transfer-requests"] });
      toast({
        title: "Transfer Created",
        description: "Stock transfer request created successfully.",
      });
    },
    onError: (error) => {
      console.error("Create transfer error:", error);
      toast({
        title: "Error",
        description: "Failed to create transfer request.",
        variant: "destructive",
      });
    },
  });
};

