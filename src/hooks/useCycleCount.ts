// Create cycle count
export const useCreateCycleCount = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (data: CreateCycleCountData) => {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) throw new Error("User not authenticated");

      const { data: cycleCount, error } = await supabase
        .from("cycle_counts")
        .insert({
          ...data,
          count_number: '', // Auto-generated by trigger
          created_by: user.id,
        })
        .select()
        .single();

      if (error) throw error;
      return cycleCount as unknown as CycleCount;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["cycle-counts"] });
      toast({
        title: "Cycle Count Created",
        description: "Cycle count session created successfully.",
      });
    },
    onError: (error) => {
      console.error("Create cycle count error:", error);
      toast({
        title: "Error",
        description: "Failed to create cycle count.",
        variant: "destructive",
      });
    },
  });
};

