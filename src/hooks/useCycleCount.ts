// Fetch all cycle counts
export const useCycleCounts = (status?: CycleCountStatus) => {
  return useQuery({
    queryKey: ["cycle-counts", status],
    queryFn: async () => {
      let query = supabase
        .from("cycle_counts")
        .select("*")
        .order("created_at", { ascending: false });

      if (status) {
        query = query.eq("status", status);
      }

      const { data, error } = await query;
      if (error) throw error;
      return data as unknown as CycleCount[];
    },
  });
};

// Fetch single cycle count
export const useCycleCount = (countId: string | undefined) => {
  return useQuery({
    queryKey: ["cycle-count", countId],
    queryFn: async () => {
      if (!countId) return null;

      const { data, error } = await supabase
        .from("cycle_counts")
        .select("*")
        .eq("id", countId)
        .single();

      if (error) throw error;
      return data as unknown as CycleCount;
    },
    enabled: !!countId,
  });
};

// Fetch cycle count items
export const useCycleCountItems = (countId: string | undefined) => {
  return useQuery({
    queryKey: ["cycle-count-items", countId],
    queryFn: async () => {
      if (!countId) return [];

      const { data, error } = await supabase
        .from("cycle_count_items")
        .select(`
          *,
          warehouse_items(
            id,
            item_name,
            unit_of_measure,
            current_stock,
            unit_cost,
            catalog:warehouse_item_catalog!warehouse_items_catalog_item_id_fkey(item_code)
          ),
          warehouse_bins (
            id,
            bin_code,
            location_id
          )
        `)
        .eq("cycle_count_id", countId)
        .order("created_at", { ascending: true });

      if (error) throw error;
      return data as any[];
    },
    enabled: !!countId,
  });
};

