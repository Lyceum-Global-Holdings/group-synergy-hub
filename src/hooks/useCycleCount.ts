// Post adjustments from cycle count
export const usePostCycleCountAdjustments = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async ({ countId, itemIds }: { countId: string; itemIds: string[] }) => {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) throw new Error("User not authenticated");

      // Get items with variance
      const { data: items, error: itemsError } = await supabase
        .from("cycle_count_items")
        .select("*")
        .eq("cycle_count_id", countId)
        .in("id", itemIds);

      if (itemsError) throw itemsError;

      // Process each item with variance
      for (const item of items || []) {
        if (item.variance_quantity && item.variance_quantity !== 0) {
          // Get current stock
          const { data: warehouseItem } = await supabase
            .from("warehouse_items_full")
            .select("current_stock")
            .eq("id", item.warehouse_item_id)
            .single();

          const currentStock = warehouseItem?.current_stock || 0;

          // Create stock transaction
          const { data: transaction } = await supabase
            .from("stock_transactions")
            .insert({
              item_id: item.warehouse_item_id,
              transaction_type: 'adjustment',
              reference_type: 'manual',
              reference_id: countId,
              quantity_change: item.variance_quantity,
              quantity_before: currentStock,
              quantity_after: currentStock + item.variance_quantity,
              notes: `Cycle Count Adjustment - ${item.variance_reason || 'Variance detected'}`,
              created_by: user.id,
            })
            .select()
            .single();

          // Create adjustment record
          await supabase
            .from("cycle_count_adjustments")
            .insert({
              cycle_count_id: countId,
              cycle_count_item_id: item.id,
              adjustment_type: item.variance_quantity > 0 ? 'increase' : 'decrease',
              adjustment_quantity: Math.abs(item.variance_quantity),
              adjustment_value: item.variance_value,
              reason: item.variance_reason || 'Cycle count variance',
              stock_transaction_id: transaction?.id,
              approved_by: user.id,
              approved_date: new Date().toISOString(),
              created_by: user.id,
            });

          // Update item status
          await supabase
            .from("cycle_count_items")
            .update({ status: 'adjusted' })
            .eq("id", item.id);
        }
      }
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["cycle-counts"] });
      queryClient.invalidateQueries({ queryKey: ["cycle-count-items"] });
      queryClient.invalidateQueries({ queryKey: ["warehouse-items"] });
      queryClient.invalidateQueries({ queryKey: ["stock-transactions"] });
      toast({
        title: "Adjustments Posted",
        description: "Stock adjustments posted successfully.",
      });
    },
    onError: (error) => {
      console.error("Post adjustments error:", error);
      toast({
        title: "Error",
        description: "Failed to post adjustments.",
        variant: "destructive",
      });
    },
  });
};
