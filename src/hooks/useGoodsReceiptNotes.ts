export interface GrnBinAllocationInput {
  warehouse_item_id: string;
  bin_id: string;
  location_id?: string | null;
  quantity: number;
}

export const useApproveGoodsReceiptNote = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async ({
      id,
      binAllocations,
      itemLinks,
    }: {
      id: string;
      binAllocations: GrnBinAllocationInput[];
      itemLinks?: Record<string, string>;
    }) => {
      // Persist any newly-linked warehouse_item_id back to grn_items first so
      // the RPC sees the resolved links. New per-company inventory rows are
      // created INSIDE the RPC — never here.
      if (itemLinks && Object.keys(itemLinks).length > 0) {
        for (const [grnItemId, warehouseItemId] of Object.entries(itemLinks)) {
          const { error: linkError } = await supabase
            .from('grn_items')
            .update({ warehouse_item_id: warehouseItemId })
            .eq('id', grnItemId);
          if (linkError) throw linkError;
        }
      }

      const payload = binAllocations
        .filter((a) => a.warehouse_item_id && a.bin_id && a.quantity > 0)
        .map((a) => ({
          warehouse_item_id: a.warehouse_item_id,
          bin_id: a.bin_id,
          location_id: a.location_id ?? null,
          quantity: a.quantity,
        }));

      const { data, error } = await supabase.rpc(
        'approve_grn_with_allocations' as any,
        { p_grn_id: id, p_allocations: payload as any }
      );
      if (error) throw error;
      return data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-notes'] });
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-note'] });
      queryClient.invalidateQueries({ queryKey: ['grn-summary'] });
      queryClient.invalidateQueries({ queryKey: ['warehouse-items'] });
      queryClient.invalidateQueries({ queryKey: ['stock-transactions'] });
      queryClient.invalidateQueries({ queryKey: ['warehouse-bins'] });
      queryClient.invalidateQueries({ queryKey: ['warehouse-bin-allocations'] });
      toast({
        title: 'Success',
        description: 'GRN approved and stock allocated to bins successfully.',
      });
    },
    onError: (error: Error) => {
      toast({
        title: 'Error',
        description: error.message,
        variant: 'destructive',
      });
    },
  });
};


export const useDeleteGoodsReceiptNote = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (id: string) => {
      // Delete items first
      const { error: itemsError } = await supabase
        .from('grn_items')
        .delete()
        .eq('grn_id', id);

      if (itemsError) throw itemsError;

      // Delete GRN
      const { error } = await supabase
        .from('goods_receipt_notes')
        .delete()
        .eq('id', id)
        .eq('status', 'draft');

      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-notes'] });
      queryClient.invalidateQueries({ queryKey: ['grn-summary'] });
      toast({
        title: 'Success',
        description: 'GRN deleted successfully',
      });
    },
    onError: (error: Error) => {
      toast({
        title: 'Error',
        description: error.message,
        variant: 'destructive',
      });
    },
  });
};

export const useRejectGoodsReceiptNote = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (input: { id: string; reason: GrnRejectionReason; notes?: string }) => {
      const { data, error } = await supabase.rpc('reject_goods_receipt_note' as any, {
        _grn_id: input.id,
        _reason: input.reason,
        _notes: input.notes ?? null,
      });
      if (error) throw error;
      return data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-notes'] });
      queryClient.invalidateQueries({ queryKey: ['grn'] });
      queryClient.invalidateQueries({ queryKey: ['grn-summary'] });
      toast({ title: 'GRN rejected', description: 'The GRN has been rejected and recorded.' });
    },
    onError: (error: Error) => {
      toast({ title: 'Rejection failed', description: error.message, variant: 'destructive' });
    },
  });
};

/**
 * Send a rejected GRN back to draft so the creator can edit and resubmit.
 * Follows SAP/Oracle/D365 rework workflow.
 */
export const useReopenGoodsReceiptNote = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (id: string) => {
      const { data, error } = await supabase.rpc('reopen_grn_draft' as any, { p_grn_id: id });
      if (error) throw error;
      return data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-notes'] });
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-note'] });
      queryClient.invalidateQueries({ queryKey: ['grn'] });
      queryClient.invalidateQueries({ queryKey: ['grn-summary'] });
      toast({ title: 'Reopened as draft', description: 'You can now edit and resubmit this GRN.' });
    },
    onError: (error: Error) => {
      toast({ title: 'Reopen failed', description: error.message, variant: 'destructive' });
    },
  });
};
