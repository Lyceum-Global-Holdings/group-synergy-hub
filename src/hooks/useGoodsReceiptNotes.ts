export const useGrnSummary = (companyId?: string) => {
  return useQuery({
    queryKey: ['grn-summary', companyId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from('goods_receipt_notes')
        .select('id, status, total_value, created_at')
        .eq('company_id', companyId || '');

      if (error) throw error;

      const currentMonth = new Date().getMonth();
      const currentYear = new Date().getFullYear();

      const summary: GrnSummary = {
        total_grns: data.length,
        pending_approval: data.filter(g => g.status === 'submitted').length,
        approved_this_month: data.filter(g => {
          const grnDate = new Date(g.created_at);
          return g.status === 'approved' && 
                 grnDate.getMonth() === currentMonth && 
                 grnDate.getFullYear() === currentYear;
        }).length,
        total_value: data.reduce((sum, g) => sum + (g.total_value || 0), 0),
      };

      return summary;
    },
    enabled: !!companyId,
  });
};

export const useCreateGoodsReceiptNote = () => {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (data: CreateGrnData) => {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) throw new Error('Not authenticated');

      // Create GRN header (grn_number is auto-generated by trigger)
      const { data: grn, error: grnError } = await supabase
        .from('goods_receipt_notes')
        .insert({
          grn_date: data.grn_date,
          po_id: data.po_id || null,
          po_number: data.po_number || null,
          supplier_id: data.supplier_id || null,
          supplier_name: data.supplier_name || null,
          supplier_address: data.supplier_address || null,
          invoice_number: data.invoice_number,
          invoice_date: data.invoice_date,
          invoice_document_url: data.invoice_document_url,
          remarks: data.remarks,
          status: data.status,
          company_id: data.company_id || null,
          created_by: user.id,
        } as any)
        .select()
        .single();

      if (grnError) throw grnError;

      // Look up warehouse_item_id for items that have item_code but no warehouse_item_id
      const enrichedItems = await Promise.all(
        data.items.map(async (item) => {
          let warehouseItemId = item.warehouse_item_id;
          
          // If no warehouse_item_id but has item_code, look it up
          if (!warehouseItemId && item.item_code) {
            const { data: warehouseItem } = await supabase
              .from('warehouse_items')
              .select('id')
              .eq('item_code', item.item_code)
              .or(`company_id.eq.${data.company_id},company_id.is.null`)
              .limit(1)
              .maybeSingle();
            
            if (warehouseItem) {
              warehouseItemId = warehouseItem.id;
            }
          }
          
          return {
            grn_id: grn.id,
            po_item_id: item.po_item_id,
            warehouse_item_id: warehouseItemId,
            item_code: item.item_code,
            item_name: item.item_name,
            description: item.description,
            unit_of_measure: item.unit_of_measure,
            quantity_ordered: item.quantity_ordered,
            quantity_received: item.quantity_received,
            unit_price: item.unit_price,
            total_cost: item.total_cost,
            quality_status: item.quality_status,
            remarks: item.remarks,
            // Batch tracking fields
            batch_number: item.batch_number || null,
            manufacturing_date: item.manufacturing_date || null,
            expiry_date: item.expiry_date || null,
          };
        })
      );

      const { error: itemsError } = await supabase
        .from('grn_items')
        .insert(enrichedItems);

      if (itemsError) throw itemsError;

      return grn;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['goods-receipt-notes'] });
      queryClient.invalidateQueries({ queryKey: ['grn-summary'] });
      queryClient.invalidateQueries({ queryKey: ['purchase-orders'] });
      queryClient.invalidateQueries({ queryKey: ['warehouse-items'] });
      queryClient.invalidateQueries({ queryKey: ['stock-transactions'] });
      toast({
        title: 'Success',
        description: 'Goods Receipt Note created successfully',
      });
    },
    onError: (error: Error) => {
      toast({
        title: 'Error',
        description: error.message,
        variant: 'destructive',
      });
    },
  });
};

