export const useGoodsReceiptNotes = (companyId?: string, locationId?: string | null) => {
  return useQuery({
    queryKey: ['goods-receipt-notes', companyId, locationId],
    queryFn: async () => {
      let query = supabase
        .from('goods_receipt_notes')
        .select(`
          *,
          warehouse_locations(name),
          purchase_order:purchase_orders(po_number, supplier:suppliers(name)),
          created_by_profile:profiles!goods_receipt_notes_created_by_profile_fkey(full_name),
          received_by_profile:profiles!goods_receipt_notes_received_by_profile_fkey(full_name),
          approved_by_profile:profiles!goods_receipt_notes_approved_by_profile_fkey(full_name),
          grn_items(
            id,
            grn_id,
            item_code,
            item_name,
            description,
            warehouse_item_id,
            catalog_item_id,
            catalog:warehouse_item_catalog!grn_items_catalog_item_id_fkey(item_code, name),
            po_item_id,
            quantity_ordered,
            quantity_received,
            unit_of_measure,
            unit_price,
            total_cost,
            quality_status,
            remarks,
            batch_number,
            manufacturing_date,
            expiry_date,
            created_at,
            updated_at
          )
        `)
        .order('created_at', { ascending: false });

      if (companyId) {
        query = query.eq('company_id', companyId);
      }
      if (locationId) {
        query = (query as any).eq('location_id', locationId);
      }

      const { data, error } = await query;

      if (error) throw error;
      return data as any;
    },
    enabled: !!companyId,
  });
};

