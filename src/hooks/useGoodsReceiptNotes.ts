import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';
import { GoodsReceiptNote, CreateGrnData, GrnSummary } from '@/types/grn';
import { useToast } from '@/hooks/use-toast';

export const useGoodsReceiptNotes = (companyId?: string) => {
  return useQuery({
    queryKey: ['goods-receipt-notes', companyId],
    queryFn: async () => {
      let query = supabase
        .from('goods_receipt_notes')
        .select(`
          *,
          purchase_order:purchase_orders(po_number, supplier:suppliers(name)),
          created_by_profile:profiles!goods_receipt_notes_created_by_profile_fkey(full_name),
          received_by_profile:profiles!goods_receipt_notes_received_by_profile_fkey(full_name),
          approved_by_profile:profiles!goods_receipt_notes_approved_by_profile_fkey(full_name),
          grn_items(
            id,
            grn_id,
            item_code,
            item_name,
            description,
            warehouse_item_id,
            po_item_id,
            quantity_ordered,
            quantity_received,
            unit_of_measure,
            unit_price,
            total_cost,
            quality_status,
            remarks,
            created_at,
            updated_at
          )
        `)
        .order('created_at', { ascending: false });

      if (companyId) {
        query = query.eq('company_id', companyId);
      }

      const { data, error } = await query;

      if (error) throw error;
      return data as any;
    },
    enabled: !!companyId,
  });
};

