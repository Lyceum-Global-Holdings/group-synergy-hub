// Fetch quotes for a request
export function useSupplierQuotes(requestId?: string) {
  return useQuery({
    queryKey: ["supplier-quotes", requestId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("supplier_quotes")
        .select(`
          *,
          items:supplier_quote_items(*),
          supplier:suppliers(id, name, supplier_code)
        `)
        .eq("request_id", requestId!)
        .order("submission_date", { ascending: false });

      if (error) throw error;
      return data as SupplierQuote[];
    },
    enabled: !!requestId,
  });
}

