// Create RFQ/RFP request
export function useCreateRfqRfpRequest() {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async (data: CreateRfqRfpData) => {
      const { items, invited_supplier_ids, ...requestData } = data;

      // Get current user
      const user = getCachedUser();
      if (!user) throw new Error("Not authenticated");

      // Create the request
      const { data: request, error: requestError } = await supabase
        .from("rfq_rfp_requests")
        .insert([{
          ...requestData,
          request_number: '', // Will be auto-generated by trigger
          created_by: user.id,
        }])
        .select()
        .single();

      if (requestError) throw requestError;

      // Create items
      if (items.length > 0) {
        const itemsToInsert = items.map((item, index) => ({
          ...item,
          request_id: request.id,
          line_number: index + 1,
        }));

        const { error: itemsError } = await supabase
          .from("rfq_rfp_items")
          .insert(itemsToInsert);

        if (itemsError) throw itemsError;
      }

      // Invite suppliers
      if (invited_supplier_ids && invited_supplier_ids.length > 0) {
        const invitations = invited_supplier_ids.map(supplier_id => ({
          request_id: request.id,
          supplier_id,
        }));

        const { error: invitationsError } = await supabase
          .from("rfq_rfp_invited_suppliers")
          .insert(invitations);

        if (invitationsError) throw invitationsError;
      }

      return request;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["rfq-rfp-requests"] });
      toast({
        title: "Success",
        description: "RFQ/RFP request created successfully",
      });
    },
    onError: (error: Error) => {
      toast({
        title: "Error",
        description: error.message,
        variant: "destructive",
      });
    },
  });
}

// Update RFQ/RFP request
export function useUpdateRfqRfpRequest() {
  const queryClient = useQueryClient();
  const { toast } = useToast();

  return useMutation({
    mutationFn: async ({ id, ...data }: Partial<RfqRfpRequest> & { id: string }) => {
      const { data: updated, error } = await supabase
        .from("rfq_rfp_requests")
        .update(data)
        .eq("id", id)
        .select()
        .single();

      if (error) throw error;
      return updated;
    },
    onSuccess: (_, variables) => {
      queryClient.invalidateQueries({ queryKey: ["rfq-rfp-requests"] });
      queryClient.invalidateQueries({ queryKey: ["rfq-rfp-request", variables.id] });
      toast({
        title: "Success",
        description: "RFQ/RFP request updated successfully",
      });
    },
    onError: (error: Error) => {
      toast({
        title: "Error",
        description: error.message,
        variant: "destructive",
      });
    },
  });
}

