export const useCompletePutaway = () => {
  const { toast } = useToast();
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (putawayId: string) => {
      const user = getCachedUser();
      if (!user) throw new Error('User not authenticated');

      // Get all pending items
      const { data: items, error: itemsError } = await supabase
        .from('putaway_items')
        .select('*')
        .eq('putaway_id', putawayId)
        .eq('status', 'pending');

      if (itemsError) throw itemsError;

      // Update bin quantities and create stock transactions for each item
      for (const item of items || []) {
        if (item.to_bin_id) {
          // Get current bin quantity
          const { data: binData } = await supabase
            .from('warehouse_bins')
            .select('current_quantity')
            .eq('id', item.to_bin_id)
            .single();

          const currentQuantity = binData?.current_quantity || 0;
          const newQuantity = currentQuantity + item.quantity;

          // Update bin quantity directly
          const { error: binError } = await supabase
            .from('warehouse_bins')
            .update({ current_quantity: newQuantity })
            .eq('id', item.to_bin_id);

          if (binError) {
            console.error('Error updating bin quantity:', binError);
          }

          // Create stock transaction
          const { error: transactionError } = await supabase
            .from('stock_transactions')
            .insert([{
              item_id: item.warehouse_item_id,
              transaction_type: 'transfer_in',
              reference_type: 'transfer',
              reference_id: putawayId,
              quantity_change: item.quantity,
              quantity_before: 0,
              quantity_after: item.quantity,
              notes: `Putaway to bin`,
              created_by: user.id
            }]);

          if (transactionError) {
            console.error('Error creating stock transaction:', transactionError);
          }
        }

        // Mark item as completed
        await supabase
          .from('putaway_items')
          .update({ status: 'completed' })
          .eq('id', item.id);
      }

      // Update putaway record
      const { data, error } = await supabase
        .from('putaway_records')
        .update({
          status: 'completed',
          completed_date: new Date().toISOString(),
          completed_by: user.id
        })
        .eq('id', putawayId)
        .select()
        .single();

      if (error) throw error;
      return data as PutawayRecord;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['putaway-records'] });
      queryClient.invalidateQueries({ queryKey: ['warehouse-bins'] });
      toast({
        title: "Success",
        description: "Putaway completed successfully",
      });
    },
    onError: (error) => {
      console.error('Error completing putaway:', error);
      toast({
        title: "Error",
        description: "Failed to complete putaway",
        variant: "destructive",
      });
    }
  });
};

