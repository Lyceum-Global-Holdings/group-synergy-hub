import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';
import { getCachedUser } from "@/lib/currentUser";
import { PutawayRecord, PutawayItem, CreatePutawayRecordData, CreatePutawayItemData } from '@/types/putaway';
import { useToast } from '@/hooks/use-toast';

export const usePutawayRecords = (status?: string) => {
  const { toast } = useToast();

  return useQuery({
    queryKey: ['putaway-records', status],
    queryFn: async () => {
      let query = supabase
        .from('putaway_records')
        .select('*')
        .order('created_at', { ascending: false });

      if (status) {
        query = query.eq('status', status);
      }

      const { data, error } = await query;
      if (error) throw error;
      return data as PutawayRecord[];
    }
  });
};

export const usePutawayItems = (putawayId: string) => {
  return useQuery({
    queryKey: ['putaway-items', putawayId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from('putaway_items')
        .select('*')
        .eq('putaway_id', putawayId)
        .order('putaway_sequence', { ascending: true });

      if (error) throw error;
      return data as PutawayItem[];
    },
    enabled: !!putawayId
  });
};

export const useCreatePutaway = () => {
  const { toast } = useToast();
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (putawayData: CreatePutawayRecordData) => {
      const user = getCachedUser();
      if (!user) throw new Error('User not authenticated');

      const { data, error } = await supabase
        .from('putaway_records')
        .insert([{
          putaway_number: '', // Will be auto-generated by trigger
          ...putawayData,
          created_by: user.id
        }])
        .select()
        .single();

      if (error) throw error;
      return data as PutawayRecord;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['putaway-records'] });
      toast({
        title: "Success",
        description: "Putaway created successfully",
      });
    },
    onError: (error) => {
      console.error('Error creating putaway:', error);
      toast({
        title: "Error",
        description: "Failed to create putaway",
        variant: "destructive",
      });
    }
  });
};

